// Package music holds the provider-agnostic domain: entities and the
// MusicProvider port implemented by each streaming service client.
package music

import (
	"context"
	"errors"
)

// ErrCredentialsExpired is returned by a provider when the service rejected
// the saved credentials (expired or revoked). Match it with errors.Is.
var ErrCredentialsExpired = errors.New("credentials expired")

type AlbumType string

const (
	AlbumTypeAlbum       AlbumType = "album"
	AlbumTypeEP          AlbumType = "ep"
	AlbumTypeCompilation AlbumType = "compilation"
	AlbumTypeSingle      AlbumType = "single"
	AlbumTypeUnknown     AlbumType = "unknown"
)

// Song is a track matched on a provider.
type Song struct {
	ID    string
	Title string
	Album string
}

// Candidate is a search result for a song on a provider.
type Candidate struct {
	TrackID   string
	Title     string
	Artist    string
	Album     string
	AlbumType AlbumType
}

// Playlist is a playlist created on a provider.
type Playlist struct {
	ID  string
	URL string
}

// MusicProvider is the port implemented by each streaming service.
type MusicProvider interface {
	// SearchCandidates returns up to ~10 candidates for a song title by an artist.
	SearchCandidates(ctx context.Context, title string, artist string) ([]Candidate, error)
	// CreatePlaylist creates a playlist; description may be empty.
	CreatePlaylist(ctx context.Context, title string, description string) (*Playlist, error)
	// AddTracks adds tracks to a playlist, keeping the given order.
	AddTracks(ctx context.Context, playlistID string, trackIDs []string) error
}

// Authenticator is the port that gets a provider ready to use. Implementations
// prompt for any missing setup, load saved credentials and obtain a valid
// session. It is idempotent so it can be called again to re-authenticate.
type Authenticator interface {
	Authenticate(ctx context.Context) error
	// Reauthenticate obtains fresh credentials, ignoring any saved ones, and
	// persists them. It is called after a provider returned ErrCredentialsExpired.
	Reauthenticate(ctx context.Context) error
}

var DefaultPlaylistDescription = "Generated by 'Setlist to Playlist' script by @mathcale"

type CreatePlaylistInput struct {
	Title       string
	Description *string
}

func (in CreatePlaylistInput) GetDescription() string {
	if in.Description == nil || *in.Description == "" {
		return DefaultPlaylistDescription
	}

	return *in.Description
}

type AddTracksInput struct {
	PlaylistID string
	Tracks     []Song
}

type FetchSongsOutput struct {
	Artist  string
	Songs   []Song
	Skipped []string
}
